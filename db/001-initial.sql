CREATE TABLE IF NOT EXISTS personal_records (
 user_id text NOT NULL, spot_id text NOT NULL, payload text NOT NULL,
 revision integer NOT NULL DEFAULT 1, updated_at text NOT NULL,
 PRIMARY KEY(user_id,spot_id)
);
CREATE TABLE IF NOT EXISTS preferences (
 user_id text PRIMARY KEY, payload text NOT NULL DEFAULT '{}', updated_at text NOT NULL
);
CREATE TABLE IF NOT EXISTS availability_overrides (
 spot_id text PRIMARY KEY, payload text NOT NULL, revision integer NOT NULL,
 updated_at text NOT NULL, updated_by text NOT NULL, change_id text NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS availability_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 spot_id text NOT NULL, payload text NOT NULL, revision integer NOT NULL,
 actor_id text NOT NULL, changed_at text NOT NULL, change_id text NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS scoring_settings (
 id text PRIMARY KEY, payload text NOT NULL, revision integer NOT NULL,
 updated_at text NOT NULL, updated_by text NOT NULL
);
CREATE TABLE IF NOT EXISTS account_links (
 auth_user_id text PRIMARY KEY, legacy_user_id text NOT NULL UNIQUE, linked_at timestamptz NOT NULL DEFAULT now()
);
